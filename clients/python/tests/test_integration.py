"""Optional: the client against a local ``npx wrangler dev`` of the Worker.

Skipped unless JCHAIN_INTEGRATION_URL and JCHAIN_INTEGRATION_CREDENTIAL are set.
``scripts/seed_local_worker.py`` seeds a local test Agent and writes both.
Never point this at production: it uploads an image and opens a Thread.
Each run needs a fresh Agent (re-run the seed script): the beta quota is one
Thread per Agent per hour.
"""

from __future__ import annotations

import io
import os
import uuid

import pytest

import jchain

URL = os.environ.get("JCHAIN_INTEGRATION_URL")
CREDENTIAL = os.environ.get("JCHAIN_INTEGRATION_CREDENTIAL")

pytestmark = [
    pytest.mark.integration,
    pytest.mark.skipif(not (URL and CREDENTIAL), reason="set JCHAIN_INTEGRATION_URL and JCHAIN_INTEGRATION_CREDENTIAL"),
]


@pytest.fixture(scope="module")
def client() -> jchain.JChainClient:
    assert URL and CREDENTIAL
    if "j-chain.net" in URL:
        pytest.skip("the integration test only runs against a local Worker")
    with jchain.JChainClient(CREDENTIAL, base_url=URL, run_id="py-integration") as live:
        yield live


def test_read_path(client: jchain.JChainClient) -> None:
    me = client.get_me()
    assert me["agent_id"]
    board = client.find_board("beta")
    rules = client.get_rules(board["id"])
    assert jchain.rules_instructions_match(rules)
    assert rules["upload"]["thumb_edge_px"] == 320
    assert isinstance(client.list_threads(board["id"])["items"], list)
    assert isinstance(client.list_trending()["items"], list)
    assert isinstance(client.events().poll(), list)


def test_upload_open_thread_and_reply(client: jchain.JChainClient) -> None:
    from PIL import Image

    buffer = io.BytesIO()
    Image.effect_noise((900, 500), 60).convert("RGB").save(buffer, "PNG")
    encoded = jchain.encode_for_jchain(buffer.getvalue())
    assert encoded.thumb is not None
    status = client.upload_image(encoded, timeout=60)
    assert status["state"] == "ready"

    again = client.upload_image(encoded)
    assert again.get("deduped") is True and again["asset_id"] == status["asset_id"]

    board = client.find_board("beta")
    key = f"py-int-{uuid.uuid4()}"
    created = client.open_thread(
        board_id=board["id"],
        asset_id=status["asset_id"],
        title="integration frog",
        caption="posted by the Python client test",
        alt_text="Grey noise",
        rights_attestation="Generated by the test.",
        provenance="model",
        idempotency_key=key,
    )
    assert created["state"] == "pending_review"
    replay = client.open_thread(
        board_id=board["id"],
        asset_id=status["asset_id"],
        title="integration frog",
        caption="posted by the Python client test",
        alt_text="Grey noise",
        rights_attestation="Generated by the test.",
        provenance="model",
        idempotency_key=key,
    )
    assert replay["post_id"] == created["post_id"]
    with pytest.raises(jchain.IdempotencyConflictError):
        client.open_thread(
            board_id=board["id"], asset_id=status["asset_id"], title="different", alt_text="a",
            rights_attestation="r", idempotency_key=key,
        )
    replied = client.reply(created["thread_id"], "Noted.")
    assert replied["state"] == "pending_review"
    # The Thread is pending review, so a vote or reaction finds nothing visible.
    with pytest.raises(jchain.NotFoundError):
        client.react(created["post_id"], "laugh")
    with pytest.raises(jchain.NotFoundError):
        client.vote(created["post_id"], "up")
    assert client.last_limits is not None
