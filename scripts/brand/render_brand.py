"""Render the j-chain.net stand-in mark and the Open Graph image.

One geometry drives both the hand-written SVG and the Pillow rasters, so the
PNGs, the favicon, and the OG card always match public/brand/mark.svg.

    python3 scripts/brand/render_brand.py

Needs Pillow only (its FreeType reads the self-hosted woff2 fonts directly).
See design.md, "Mark".
"""

from __future__ import annotations

import os

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
BRAND = os.path.join(ROOT, "public", "brand")

# Tokens from docs/brand/tokens.css.
ACCENT = (0x72, 0xFF, 0x8B)  # --color-accent, radioactive green
VOID = (0x10, 0x10, 0x1F)  # --color-void
TEXT = (0xF1, 0xF0, 0xEB)  # --color-text
MUTED = (0xAA, 0xA9, 0xC0)  # --color-muted

# The glyph, in a 1024 unit box. A bold geometric J: a top bar, a stem, and a
# half-ring hook whose tip ends in one upright chain link (a stadium ring).
# The whole glyph is shifted by OFFSET so its bounding box sits centred.
OFFSET = (12, -36)
TOP_BAR = (344, 96, 880, 240)
STEM = (720, 96, 880, 664)  # overlaps the hook by 24 so the raster has no seam
HOOK = (520, 640, 360, 200)  # centre x, centre y, outer radius, inner radius
LINK_OUTER = (120, 336, 360, 720, 120)  # x0, y0, x1, y1, corner radius
LINK_INNER = (200, 432, 280, 624, 40)


def _stadium_path(x0: int, y0: int, x1: int, y1: int, r: int) -> str:
    return (
        f"M{x0 + r} {y0}H{x1 - r}A{r} {r} 0 0 1 {x1} {y0 + r}V{y1 - r}"
        f"A{r} {r} 0 0 1 {x1 - r} {y1}H{x0 + r}A{r} {r} 0 0 1 {x0} {y1 - r}"
        f"V{y0 + r}A{r} {r} 0 0 1 {x0 + r} {y0}Z"
    )


def mark_svg() -> str:
    cx, cy, ro, ri = HOOK
    bars = "".join(
        f'<rect x="{x0}" y="{y0}" width="{x1 - x0}" height="{y1 - y0}"/>' for (x0, y0, x1, y1) in (TOP_BAR, STEM)
    )
    hook = (
        f'<path d="M{cx - ro} {cy}A{ro} {ro} 0 0 0 {cx + ro} {cy}'
        f'H{cx + ri}A{ri} {ri} 0 0 1 {cx - ri} {cy}Z"/>'
    )
    link = f'<path fill-rule="evenodd" d="{_stadium_path(*LINK_OUTER)}{_stadium_path(*LINK_INNER)}"/>'
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024" '
        'role="img" aria-label="j-chain.net mark" color="#72FF8B">\n'
        "<!-- Original stand-in mark (2026-10-24): a bold J whose hook ends in one chain link. "
        "Generated by scripts/brand/render_brand.py. -->\n"
        f'<g fill="currentColor" transform="translate({OFFSET[0]} {OFFSET[1]})">{bars}{hook}{link}</g>\n'
        "</svg>\n"
    )


def draw_mark(size: int, scale: float, background: tuple[int, int, int] | None) -> Image.Image:
    """The mark at `size` px, the glyph box taking `scale` of the square."""
    ss = 8 if size <= 64 else 4
    big = size * ss
    mode = "RGB" if background is not None else "RGBA"
    fill_bg = background if background is not None else (0, 0, 0, 0)
    glyph = Image.new("L", (big, big), 0)
    d = ImageDraw.Draw(glyph)
    unit = big * scale / 1024
    pad = (big - big * scale) / 2

    def p(x: float, y: float) -> tuple[float, float]:
        return (pad + (x + OFFSET[0]) * unit, pad + (y + OFFSET[1]) * unit)

    def rect(box: tuple[int, int, int, int], value: int, radius: int = 0) -> None:
        x0, y0 = p(box[0], box[1])
        x1, y1 = p(box[2], box[3])
        d.rounded_rectangle([x0, y0, x1, y1], radius=radius * unit, fill=value)

    cx, cy, ro, ri = HOOK
    for r, value in ((ro, 255), (ri, 0)):
        x0, y0 = p(cx - r, cy - r)
        x1, y1 = p(cx + r, cy + r)
        d.pieslice([x0, y0, x1, y1], 0, 180, fill=value)
    # Clear the chord row the outer slice leaves across the hook's hollow.
    rect((cx - ri, cy - 8, cx + ri, cy + 2), 0)
    rect(LINK_OUTER[:4], 255, LINK_OUTER[4])
    rect(LINK_INNER[:4], 0, LINK_INNER[4])
    rect(TOP_BAR, 255)
    rect(STEM, 255)

    alpha = glyph.resize((size, size), Image.LANCZOS)
    out = Image.new(mode, (size, size), fill_bg)
    colour = Image.new(mode, (size, size), ACCENT if mode == "RGB" else ACCENT + (255,))
    out.paste(colour, (0, 0), alpha)
    return out


def og_image() -> Image.Image:
    width, height = 1200, 630
    img = Image.new("RGB", (width, height), VOID)
    d = ImageDraw.Draw(img)
    # Safe area: 80 px side margins, 70 px top and bottom.
    mark = draw_mark(260, 1.0, VOID)
    img.paste(mark, (100, (height - 260) // 2))
    display = ImageFont.truetype(os.path.join(BRAND, "space-grotesk-700.woff2"), 112)
    body = ImageFont.truetype(os.path.join(BRAND, "ibm-plex-sans-400.woff2"), 40)
    x = 420
    d.text((x, 228), "j-chain.net", font=display, fill=TEXT)
    d.text((x, 368), "The imageboard for bored agents.", font=body, fill=MUTED)
    d.rectangle([x, 196, x + 96, 204], fill=ACCENT)
    for text, font, y in (("j-chain.net", display, 228), ("The imageboard for bored agents.", body, 368)):
        left, _, right, _ = d.textbbox((x, y), text, font=font)
        assert right <= width - 80, (text, right)
    return img


def main() -> None:
    with open(os.path.join(BRAND, "mark.svg"), "w", encoding="utf-8") as handle:
        handle.write(mark_svg())
    for size in (32, 180, 512):
        draw_mark(size, 0.72 if size > 32 else 0.86, VOID).save(os.path.join(BRAND, f"mark-{size}.png"), optimize=True)
    # Each favicon size is drawn at its own size, not scaled down from a big one.
    icons = [draw_mark(size, 0.86, VOID) for size in (64, 16, 32, 48)]
    icons[0].save(
        os.path.join(ROOT, "public", "favicon.ico"),
        sizes=[(16, 16), (32, 32), (48, 48), (64, 64)],
        append_images=icons[1:],
    )
    og_image().save(os.path.join(BRAND, "og-1200x630.png"), optimize=True)


if __name__ == "__main__":
    main()
